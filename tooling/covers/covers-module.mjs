/**
 * src/client/template-covers.mjs from the cover PNGs (<kind>-<id>.png): data URIs the client bundle carries, so the
 * inspiration library shows them with no Host call. Also runnable alone after editing a PNG by hand:
 *
 *   node tooling/covers/covers-module.mjs [<covers dir>]
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const COVERS_DIR = path.resolve(here, '../../packages/dsh-adapter/src/client/covers');
export const COVERS_MODULE = path.resolve(here, '../../packages/dsh-adapter/src/client/template-covers.mjs');

/** { word: { id: dataUri }, excel: { … } } from the directory's <kind>-<id>.png files, ids sorted. */
export function coversOf(dir = COVERS_DIR) {
  const covers = { word: {}, excel: {} };
  for (const name of readdirSync(dir).sort()) {
    const match = name.match(/^(word|excel)-([a-z0-9-]+)\.png$/);
    if (match) covers[match[1]][match[2]] = `data:image/png;base64,${readFileSync(path.join(dir, name)).toString('base64')}`;
  }
  return covers;
}

export function coversSource(covers) {
  const kind = name => `  ${name}: Object.freeze({\n${Object.entries(covers[name]).map(([id, uri]) => `    ${JSON.stringify(id)}: '${uri}',\n`).join('')}  }),\n`;
  return `// Generated by tooling/covers/render-template-covers.mjs (covers-module.mjs) from src/client/covers/*.png. Do not edit.
/** First-page covers of the built-in Word and Excel templates, rendered by the real editor: kind → template id → PNG data URI. */
export const TEMPLATE_COVERS = Object.freeze({
${kind('word')}${kind('excel')}});
`;
}

export function writeCoversModule(dir = COVERS_DIR, target = COVERS_MODULE) {
  writeFileSync(target, coversSource(coversOf(dir)));
  return target;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(writeCoversModule(process.argv[2] ? path.resolve(process.argv[2]) : COVERS_DIR));
